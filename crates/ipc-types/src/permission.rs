//! Permission request and decision schemas.

use serde::{Deserialize, Serialize};
use ts_rs::TS;

use crate::{PermissionRequestId, TransactionProposalId, WorkspaceGrantId};

/// Capability-specific operation requiring a human decision.
#[derive(Clone, Debug, Deserialize, Eq, PartialEq, Serialize, TS)]
#[serde(
    tag = "type",
    rename_all = "camelCase",
    rename_all_fields = "camelCase",
    deny_unknown_fields
)]
pub enum PermissionKind {
    /// Read bounded content from a granted workspace.
    WorkspaceRead {
        /// Existing workspace grant.
        grant_id: WorkspaceGrantId,
        /// Grant-relative path presented to the user.
        relative_path: String,
    },
    /// Apply an exact, previously staged workspace change.
    WorkspaceWrite {
        /// Existing workspace grant.
        grant_id: WorkspaceGrantId,
        /// Human-readable change summary.
        summary: String,
        /// Digest binding approval to the staged content.
        content_hash: String,
    },
    /// Make one bounded request to an external origin.
    NetworkRequest {
        /// Canonical request origin.
        origin: String,
        /// Uppercase HTTP method.
        method: String,
    },
    /// Display a transaction proposal in the trusted native review surface.
    TransactionReview {
        /// Proposal reviewed by the native surface.
        proposal_id: TransactionProposalId,
    },
}

/// A frontend-visible request for a fresh human decision.
#[derive(Clone, Debug, Deserialize, Eq, PartialEq, Serialize, TS)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
pub struct PermissionRequest {
    /// Stable permission request identifier.
    pub id: PermissionRequestId,
    /// Human-readable reason generated by trusted Rust code.
    pub reason: String,
    /// Exact capability operation under review.
    pub kind: PermissionKind,
}

/// Result of a human permission interaction.
#[derive(Clone, Debug, Deserialize, Eq, PartialEq, Serialize, TS)]
#[serde(rename_all = "camelCase")]
pub enum PermissionOutcome {
    /// The exact request was approved.
    Approved,
    /// The exact request was denied.
    Denied,
    /// The user dismissed the request without a decision.
    Dismissed,
    /// The request expired before approval.
    Expired,
}

/// Decision bound to one permission request.
#[derive(Clone, Debug, Deserialize, Eq, PartialEq, Serialize, TS)]
#[serde(rename_all = "camelCase", deny_unknown_fields)]
pub struct PermissionDecision {
    /// Permission request receiving the decision.
    pub request_id: PermissionRequestId,
    /// Human decision outcome.
    pub outcome: PermissionOutcome,
}
