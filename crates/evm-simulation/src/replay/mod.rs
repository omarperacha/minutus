/// Maintained-engine call scheme, separate from apparent delegate-call value.
#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub enum ReplayCallKind {
    /// Ordinary message call, including a real value transfer when nonzero.
    Call,
    /// Foreign code with the caller's storage and no net value transfer.
    CallCode,
    /// Foreign code retaining the original caller and apparent value.
    DelegateCall,
    /// Read-only message call.
    StaticCall,
}
/// Exact bounded frame facts generated by host replay, never child claims.
pub struct ReplayCall {
    pub(super) kind: ReplayCallKind,
    pub(super) target: String,
    pub(super) code_address: String,
    pub(super) caller: String,
    pub(super) value: String,
    pub(super) input: String,
    pub(super) output: String,
    pub(super) succeeded: bool,
    pub(super) committed: bool,
    pub(super) parent: Option<usize>,
    pub(super) depth: usize,
}
impl ReplayCall {
    /// Exact EVM call scheme.
    #[must_use]
    pub const fn kind(&self) -> ReplayCallKind {
        self.kind
    }
    /// Storage context.
    #[must_use]
    pub fn target(&self) -> &str {
        &self.target
    }
    /// Executed code account, distinct under delegate dispatch.
    #[must_use]
    pub fn code_address(&self) -> &str {
        &self.code_address
    }
    /// EVM caller, which need not be the source of a real native transfer.
    #[must_use]
    pub fn caller(&self) -> &str {
        &self.caller
    }
    /// Apparent call value. Consult `native_transfers` for actual transfers.
    #[must_use]
    pub fn value(&self) -> &str {
        &self.value
    }
    /// Exact calldata.
    #[must_use]
    pub fn input(&self) -> &str {
        &self.input
    }
    /// Exact return/revert data.
    #[must_use]
    pub fn output(&self) -> &str {
        &self.output
    }
    /// Whether this frame returned successfully.
    #[must_use]
    pub const fn succeeded(&self) -> bool {
        self.succeeded
    }
    /// Whether this frame and every ancestor succeeded.
    #[must_use]
    pub const fn committed(&self) -> bool {
        self.committed
    }
    /// Frame depth starting at one.
    #[must_use]
    pub const fn depth(&self) -> usize {
        self.depth
    }
}
/// Real committed native transfer; excludes delegate apparent value and rollback.
pub struct NativeTransfer {
    from: String,
    to: String,
    value: String,
}
impl NativeTransfer {
    /// Source native account.
    #[must_use]
    pub fn from(&self) -> &str {
        &self.from
    }
    /// Destination native account.
    #[must_use]
    pub fn to(&self) -> &str {
        &self.to
    }
    /// Exact canonical hexadecimal wei quantity.
    #[must_use]
    pub fn value(&self) -> &str {
        &self.value
    }
}
/// Opaque host execution certificate. Proof provenance is separately sealed by
/// chain-evm; there is no constructor from an isolated worker's observation.
pub struct TrustedReplayExecution {
    observation: SimulationObservation,
    calls: Vec<ReplayCall>,
    preimages: Vec<Vec<u8>>,
    writes: Vec<(String, String)>,
    sensitive: Vec<u8>,
    transfers: Vec<NativeTransfer>,
    base_application: bool,
    fee_ceiling: Option<String>,
}
impl TrustedReplayExecution {
    /// Whether this is only a fee-insensitive Base application-frame certificate.
    #[must_use]
    pub const fn is_base_application(&self) -> bool {
        self.base_application
    }
    /// Proved-snapshot all-signature maximum fee for Base application mode.
    #[must_use]
    pub fn fee_ceiling_wei(&self) -> Option<&str> {
        self.fee_ceiling.as_deref()
    }
    /// Full host-generated execution facts, with no semantic qualification flag.
    #[must_use]
    pub const fn observation(&self) -> &SimulationObservation {
        &self.observation
    }
    /// Complete ordered frame records, including reverted calls.
    #[must_use]
    pub fn calls(&self) -> &[ReplayCall] {
        &self.calls
    }
    /// Bounded exact KECCAK256 preimages, including reverted paths.
    #[must_use]
    pub fn keccak_preimages(&self) -> &[Vec<u8>] {
        &self.preimages
    }
    /// All attempted SSTORE address/slot pairs, including restored and reverted writes.
    #[must_use]
    pub fn written_slots(&self) -> &[(String, String)] {
        &self.writes
    }
    /// Encountered environment/fee-sensitive opcodes, retained conservatively.
    #[must_use]
    pub fn sensitive_opcodes(&self) -> &[u8] {
        &self.sensitive
    }
    /// Committed real CALL value transfers, independent of apparent delegate value.
    #[must_use]
    pub fn native_transfers(&self) -> &[NativeTransfer] {
        &self.transfers
    }
}

/// Re-executes with the pinned maintained engine and a map-only state witness.
/// The caller must run this synchronous bounded work on its blocking executor,
/// and independently bind every supplied fact to a verified state root.
///
/// # Errors
/// Rejects unknown state, cancellation, unsupported rules and all fixed bounds.
/// Unsigned Base still requires genuine-envelope fee handling; no alternate EVM
/// or fabricated envelope is substituted to manufacture an exact result.
pub fn replay_frozen(
    request: &SimulationRequest,
    facts: &[(StateQuery, StateValue)],
    control: &SimulationControl<'_>,
) -> Result<TrustedReplayExecution, SimulationError> {
    replay_recording(request, facts, control, None)
}
fn replay_recording(
    request: &SimulationRequest,
    facts: &[(StateQuery, StateValue)],
    control: &SimulationControl<'_>,
    missing: Option<MissingQuery>,
) -> Result<TrustedReplayExecution, SimulationError> {
    control.remaining()?;
    if facts.len() > crate::MAX_STATE_QUERIES as usize {
        return Err(SimulationError::Limit);
    }
    for (query, value) in facts {
        validate_fact(request, query, value)?;
    }
    match crate::admission::validate(request)? {
        crate::admission::Rules::Osaka | crate::admission::Rules::Amsterdam => {
            ethereum::execute(request, facts, control, missing)
        }
        crate::admission::Rules::BaseCobalt | crate::admission::Rules::BaseDenim => {
            base::execute(request, facts, control, missing)
        }
    }
}

fn validate_fact(
    request: &SimulationRequest,
    query: &StateQuery,
    value: &StateValue,
) -> Result<(), SimulationError> {
    crate::admission::validate_query(query, request.block.number)?;
    match (query, value) {
        (StateQuery::Account { .. }, StateValue::Account { balance, code, .. }) => {
            crate::admission::quantity(balance)?;
            crate::admission::data(code, 24_576)?;
        }
        (StateQuery::Storage { .. }, StateValue::Storage { value }) => {
            crate::admission::hash(value)?;
        }
        (StateQuery::BlockHash { .. }, StateValue::BlockHash { hash }) => {
            crate::admission::hash(hash)?;
        }
        _ => return Err(SimulationError::Protocol),
    }
    Ok(())
}

